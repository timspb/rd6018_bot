from pathlib import Path
import unittest


class RD6018OutputOwnerContractTests(unittest.TestCase):
    def test_exactly_one_firmware_r18_write_endpoint_remains(self):
        target = Path("esphome/rd6018.yaml").read_text(encoding="utf-8")
        lease = Path("esphome/packages/rd6018_safety_lease.yaml").read_text(encoding="utf-8")
        intrinsic = Path("esphome/packages/rd6018_intrinsic_safety.yaml").read_text(encoding="utf-8")
        owner = Path("esphome/components/rd6018_output_owner/output_owner.cpp").read_text(encoding="utf-8")
        self.assertIn("platform: rd6018_output_owner", target)
        self.assertIn("id: rd6018_output_public", target)
        self.assertNotIn("id: rd6018_safety_output\n", lease.split("switch:", 1)[-1].split("button:", 1)[0])
        self.assertNotIn("switch.turn_off: rd6018_safety_output", lease + intrinsic)
        self.assertEqual(owner.count("write_single_register(18,"), 1)
        self.assertIn("switch.turn_off: rd6018_output_public", lease)
        self.assertIn("switch.turn_off: rd6018_output_public", intrinsic)

    def test_write_ack_is_not_applied_and_readback_is_causal(self):
        lease = Path("esphome/packages/rd6018_safety_lease.yaml").read_text(encoding="utf-8")
        owner = Path("esphome/components/rd6018_output_owner/output_owner.cpp").read_text(encoding="utf-8")
        self.assertIn("on_sent(std::span<const uint8_t>", owner)
        self.assertIn("read_holding_registers(18, 1)", owner)
        self.assertIn('publish_("ACKNOWLEDGED_WAITING_READBACK")', owner)
        self.assertIn('actual == this->target_ ? "APPLIED" : "OUTCOME_UNCERTAIN"', owner)
        self.assertIn("clear_tx_queue_for_device()", owner)
        self.assertNotIn("clear_tx_queue_for_address", owner)
        self.assertIn("return false;", owner)
        self.assertIn('old_sent ? "OUTCOME_UNCERTAIN" : "CANCELED"', owner)
        self.assertIn("const uint32_t sent_ms = millis();", owner)
        self.assertIn("this->write_sent_ms_ = sent_ms;", owner)
        self.assertIn("this->read_sent_ms_ = sent_ms;", owner)
        self.assertIn("this->write_send_generation_ = generation;", owner)
        self.assertIn("this->read_send_generation_ = generation;", owner)
        self.assertIn("void OutputOwner::on_not_sent(std::span<const uint8_t> request_pdu)", owner)
        self.assertIn('this->publish_terminal_("CANCELED");', owner)
        self.assertIn('this->uncertain_("owner frame retired before transmission")', owner)
        self.assertIn("void OutputOwner::observe_readback(uint16_t value)", owner)
        self.assertIn("if (this->active_) return;", owner)
        self.assertIn("id(rd6018_output_public).observe_readback((uint16_t) x);", lease)


    def test_queue_lifecycle_and_correlation_are_fail_closed(self):
        header = Path("esphome/components/rd6018_output_owner/output_owner.h").read_text(encoding="utf-8")
        owner = Path("esphome/components/rd6018_output_owner/output_owner.cpp").read_text(encoding="utf-8")
        transport = Path("runtime/physical/transports/esp128.py").read_text(encoding="utf-8")
        self.assertIn('if (!this->write_single_register(18, enabled ? 1 : 0))', owner)
        self.assertIn('this->publish_("NOT_QUEUED")', owner)
        self.assertIn('this->publish_terminal_("NOT_QUEUED")', owner)
        self.assertIn('this->publish_terminal_(old_sent ? "OUTCOME_UNCERTAIN" : "CANCELED")', owner)
        self.assertIn('return false;', owner)
        self.assertIn('request_id == this->request_id_', owner)
        self.assertIn('this->request_id_ == "switch" && request_id != "switch"', owner)
        self.assertIn('if (request_id == "switch") return;', owner)
        self.assertIn('request_id != "switch" && this->request_id_ == request_id', owner)
        self.assertIn("std::array<ReceiptRecord, 8> receipts_", header)
        self.assertIn("find_receipt_(request_id)", owner)
        self.assertIn("publish_cached_(*cached)", owner)
        self.assertIn("remember_receipt_(state)", owner)
        self.assertIn('request_pdu[0] == 0x06', owner)
        self.assertIn('this->uncertain_("R18 readback exception")', owner)
        self.assertIn('"CANCELED"', transport)
        self.assertIn('self._output_receipts.pop(request_id, None)', transport)

    def test_native_ingress_is_static_and_probe_cadence_stays_unchanged(self):
        target = Path("esphome/rd6018.yaml").read_text(encoding="utf-8")
        telemetry = Path("esphome/packages/rd6018_telemetry_v2.yaml").read_text(encoding="utf-8")
        platform = Path("esphome/components/rd6018_output_owner/switch.py").read_text(encoding="utf-8")
        package = Path("esphome/components/rd6018_output_owner/__init__.py").read_text(encoding="utf-8")
        self.assertIn("action: rd6018_output_command", target)
        self.assertIn("request_id: string", target)
        self.assertIn("enabled: bool", target)
        self.assertIn("supports_response: none", target)
        self.assertNotIn("custom_services", target)
        self.assertIn("external_components:", target)
        self.assertIn("owner_ns = cg.esphome_ns.namespace", package)
        self.assertIn("switch.switch_schema(OutputOwner)", platform)
        self.assertIn("await switch.register_switch(var, config)", platform)
        self.assertIn("id: rd6018_output_state_code_v2", telemetry)
        self.assertIn("update_interval: 5s", target)

    def test_ovp_ocp_readbacks_and_opp_only_intrinsic_off_are_preserved(self):
        target = Path("esphome/rd6018.yaml").read_text(encoding="utf-8")
        telemetry = Path("esphome/packages/rd6018_telemetry_v2.yaml").read_text(encoding="utf-8")
        intrinsic = Path("esphome/packages/rd6018_intrinsic_safety.yaml").read_text(encoding="utf-8")
        for entity, address in (("rd6018_ovp_readback_v2", 82), ("rd6018_ocp_readback_v2", 83)):
            block = telemetry.split(f"id: {entity}", 1)[1].split("  - platform:", 1)[0]
            self.assertIn(f"address: {address}", block)
        self.assertIn("max_value: 60", target)
        self.assertIn("max_value: 18", target)
        self.assertIn("((uint16_t) protection) != 0U", intrinsic)
        self.assertIn("((uint16_t) protection) != 1U", intrinsic)
        self.assertIn("((uint16_t) protection) != 2U", intrinsic)
        self.assertIn("- interval: 5s", intrinsic)
        self.assertIn("switch.turn_off: rd6018_output_public", intrinsic)
        self.assertNotIn("protection.status in {ProtectionStatus.OVP, ProtectionStatus.OCP}", Path("runtime/safety/managed_guard.py").read_text(encoding="utf-8"))

    def test_python_native_path_preserves_ovp_ocp_readback_without_setters(self):
        physical = Path("config/physical/esp128.yaml").read_text(encoding="utf-8")
        transport = Path("runtime/physical/transports/esp128.py").read_text(encoding="utf-8")
        connector = Path("runtime/physical/connectors/esp_direct.py").read_text(encoding="utf-8")
        hass = Path("hass_api.py").read_text(encoding="utf-8")
        self.assertIn("ovp: ovp_readback_v2", physical)
        self.assertIn("ocp: ocp_readback_v2", physical)
        self.assertIn('result["ovp_readback_v2"] = result.get("ovp")', transport)
        self.assertIn('result["ocp_readback_v2"] = result.get("ocp")', transport)
        self.assertIn('"ovp_readback_v2": "ovp"', transport)
        self.assertIn('"ocp_readback_v2": "ocp"', transport)
        self.assertNotIn("async def set_ovp", connector)
        self.assertNotIn("async def set_ocp", connector)
        self.assertNotIn("async def set_ovp", hass)
        self.assertNotIn("async def set_ocp", hass)
